import React, { useState, useEffect } from 'react';
import { apiRequest, formatINR, formatDate } from '../api';
import { useAuth } from '../context/AuthContext';

export default function ReportsView() {
  const { user, isAdmin } = useAuth();
  const [reportData, setReportData] = useState(null);
  const [loading, setLoading] = useState(true);

  const fetchReport = async () => {
    try {
      setLoading(true);
      const data = await apiRequest('/reports');
      setReportData(data);
    } catch (err) {
      console.error('Error fetching report', err);
    } finally {
      setLoading(false);
    }
  };

  useEffect(() => {
    fetchReport();
  }, []);

  const handlePrint = () => {
    window.print();
  };

  const handleExportCSV = () => {
    if (!reportData?.records || reportData.records.length === 0) {
      alert('No records available');
      return;
    }

    const headers = ['Date', 'Submitted By', 'Status', 'Amount (INR)', 'Rejection Reason'];
    const rows = reportData.records.map(r => [
      `"${r.date || ''}"`,
      `"${r.submittedBy?.name || ''}"`,
      `"${r.status}"`,
      r.amount,
      `"${(r.rejectionReason || '').replace(/"/g, '""')}"`
    ]);

    const csvContent = 'data:text/csv;charset=utf-8,' + [headers.join(','), ...rows.map(e => e.join(','))].join('\n');
    const encodedUri = encodeURI(csvContent);
    const link = document.createElement('a');
    link.setAttribute('href', encodedUri);
    link.setAttribute('download', `Temple_Report_${new Date().toISOString().split('T')[0]}.csv`);
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
  };

  const summary = reportData?.summary || {};
  let records = reportData?.records || [];

  // If user is member, show only their own in report table
  if (!isAdmin) {
    records = records.filter(r => r.submittedBy?.id === user?.id);
  }

  return (
    <div className="space-y-6 max-w-4xl mx-auto">
      
      {/* Top Action Bar (Hidden during print) */}
      <div className="no-print bg-white rounded-2xl p-5 border border-slate-200/90 shadow-xs flex flex-col sm:flex-row sm:items-center justify-between gap-3">
        <div>
          <h2 className="text-base font-bold text-slate-900">
            Financial Audit Statement
          </h2>
          <p className="text-xs text-slate-500">
            Statement of temple treasury disbursements and approved bills
          </p>
        </div>

        <div className="flex items-center gap-2 self-start sm:self-auto">
          <button
            onClick={handlePrint}
            className="px-4 py-2 text-xs font-semibold text-slate-700 bg-slate-100 hover:bg-slate-200 rounded-xl transition-colors cursor-pointer border border-slate-200"
          >
            Print Statement
          </button>
          <button
            onClick={handleExportCSV}
            className="px-4 py-2 text-xs font-bold text-white bg-slate-900 hover:bg-slate-800 rounded-xl shadow-xs transition-colors cursor-pointer"
          >
            Export CSV
          </button>
        </div>
      </div>

      {/* Main Printable Statement Card */}
      <div className="bg-white rounded-2xl p-6 sm:p-8 border border-slate-200/90 shadow-sm space-y-6">
        
        {/* Printable Header */}
        <div className="border-b border-slate-200 pb-5 flex flex-col sm:flex-row sm:items-center justify-between gap-4">
          <div>
            <h1 className="text-xl font-extrabold text-slate-900 tracking-tight">
              Sri Vigneshwara Swamy Temple
            </h1>
            <p className="text-xs text-slate-500 mt-0.5">
              Official Treasury Audit Statement • Reg No: TR-2024/78901
            </p>
          </div>
          <div className="text-left sm:text-right text-xs text-slate-500">
            <p><strong>Generated on:</strong> {formatDate(new Date())}</p>
            <p><strong>Generated by:</strong> {user?.name}</p>
          </div>
        </div>

        {/* Balance Box */}
        <div className="bg-slate-50 p-4 rounded-xl border border-slate-200/90 flex items-center justify-between">
          <div>
            <span className="text-xs font-bold uppercase tracking-wider text-slate-500 block">
              Current Treasury Balance
            </span>
            <span className="text-2xl font-extrabold text-slate-900">
              {formatINR(summary.netAvailableBalance || 0)}
            </span>
          </div>

          <div className="text-right text-xs text-slate-600">
            <p>Total Inflow: <strong>{formatINR(summary.totalInflow || 0)}</strong></p>
            <p>Total Approved: <strong>{formatINR(summary.totalApproved || 0)}</strong></p>
          </div>
        </div>

        {/* Ledger Table */}
        <div className="overflow-x-auto border border-slate-200 rounded-xl">
          <table className="w-full text-left text-xs border-collapse">
            <thead className="bg-slate-100 text-slate-700 font-bold uppercase text-[10px] tracking-wider">
              <tr>
                <th className="p-3.5">Date</th>
                <th className="p-3.5">Submitted By</th>
                <th className="p-3.5">Bill Status</th>
                <th className="p-3.5">Approval</th>
                <th className="p-3.5 text-right">Amount (₹)</th>
              </tr>
            </thead>
            <tbody className="divide-y divide-slate-100 text-slate-700">
              {records.map((r) => (
                <tr key={r.id} className="hover:bg-slate-50/70 transition-colors">
                  <td className="p-3.5 whitespace-nowrap text-slate-500 font-medium">{formatDate(r.date)}</td>
                  <td className="p-3.5 font-bold text-slate-900">
                    {r.submittedBy?.name}
                    {r.rejectionReason && (
                      <span className="block text-[11px] text-rose-600 font-normal mt-0.5">
                        Reason: {r.rejectionReason}
                      </span>
                    )}
                  </td>
                  <td className="p-3.5">
                    {r.billPhotoUrl ? (
                      <span className="text-[10px] font-bold text-blue-700 bg-blue-50 px-2 py-0.5 rounded border border-blue-200">
                        Uploaded
                      </span>
                    ) : (
                      <span className="text-[10px] text-slate-400">None</span>
                    )}
                  </td>
                  <td className="p-3.5">
                    <span className={`px-2.5 py-0.5 rounded-full text-[10px] font-bold ${
                      r.status === 'APPROVED' ? 'bg-emerald-50 text-emerald-800 border border-emerald-200' :
                      r.status === 'REJECTED' ? 'bg-rose-50 text-rose-800 border border-rose-200' :
                      'bg-amber-50 text-amber-900 border border-amber-200'
                    }`}>
                      {r.status}
                    </span>
                  </td>
                  <td className="p-3.5 text-right font-extrabold text-slate-900 text-sm whitespace-nowrap">
                    {formatINR(r.amount)}
                  </td>
                </tr>
              ))}

              {records.length === 0 && (
                <tr>
                  <td colSpan="5" className="p-8 text-center text-slate-400">
                    No bill records found for the statement.
                  </td>
                </tr>
              )}
            </tbody>
          </table>
        </div>

      </div>

    </div>
  );
}
